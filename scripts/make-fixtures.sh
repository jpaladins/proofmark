#!/usr/bin/env bash
# Regenerates real DigiCert RFC 3161 fixtures and the pinned trust anchor.
# Requires openssl + curl (both ship with Git for Windows). Run: bash scripts/make-fixtures.sh
set -euo pipefail
cd "$(dirname "$0")/.."
FX=src/test/fixtures
TRUST=src/test/fixtures/digicert-trusted-root-g4.pem
TRUST_TS=src/core/trust/digicertRootG4.ts
G4_SHA256="55:2F:7B:DC:F1:A7:AF:9E:6C:E6:72:01:7F:4F:12:AB:F7:72:40:C7:8E:76:1A:C2:03:D1:D9:D2:0A:C8:99:88"

printf 'ProofMark fixture\n' > "$FX/data.bin"
openssl ts -query -data "$FX/data.bin" -sha256 -cert -out "$FX/data.tsq"
curl -sS --fail -H 'Content-Type: application/timestamp-query' --data-binary @"$FX/data.tsq" \
  http://timestamp.digicert.com -o "$FX/data.tsr"
openssl dgst -sha256 -r "$FX/data.bin" | cut -d' ' -f1 | tr -d '\n' > "$FX/data.sha256"

tmp=$(mktemp)
curl -sS --fail https://cacerts.digicert.com/DigiCertTrustedRootG4.crt -o "$tmp"
openssl x509 -inform der -in "$tmp" -out "$TRUST"
rm -f "$tmp"
fp=$(openssl x509 -in "$TRUST" -noout -fingerprint -sha256 | cut -d= -f2)
if [ "$fp" != "$G4_SHA256" ]; then
  echo "DigiCert Trusted Root G4 fingerprint mismatch: $fp" >&2
  rm -f "$TRUST"
  exit 1
fi
{
  echo '// Generated by scripts/make-fixtures.sh after checking the SHA-256 fingerprint. Do not edit.'
  echo "// SHA-256: $G4_SHA256"
  echo 'export default `'"$(cat "$TRUST")"'`'
} > "$TRUST_TS"
openssl ts -reply -in "$FX/data.tsr" -text | head -20
echo "fixtures written; root fingerprint OK"
